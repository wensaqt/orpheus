/*
 * Builds src/lib/passwords/commonPasswords.ts: the most used passwords that the length rule
 * alone would let through, from SecLists (MIT licence, Daniel Miessler).
 *
 *   pnpm passwords:blocklist
 *
 * Shorter passwords need no list: the minimum length already refuses them.
 */
import { writeFileSync } from 'node:fs'

import { MAX_PASSWORD_LENGTH, MIN_PASSWORD_LENGTH } from '../src/lib/users'

const BASE =
  'https://raw.githubusercontent.com/danielmiessler/SecLists/master/Passwords/Common-Credentials/'
const SOURCES = [
  { name: 'xato-net-10-million-passwords-1000000.txt', limit: 300_000 },
  { name: '100k-most-used-passwords-NCSC.txt', limit: Infinity },
]
const OUTPUT = 'src/lib/passwords/commonPasswords.ts'

const words = new Set<string>()
for (const { name, limit } of SOURCES) {
  const response = await fetch(BASE + name)
  if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`)
  const lines = (await response.text()).split(/\r?\n/).slice(0, limit)
  for (const line of lines) {
    const word = line.trim().toLowerCase()
    // Length in characters, not bytes
    const length = [...word].length
    if (length >= MIN_PASSWORD_LENGTH && length <= MAX_PASSWORD_LENGTH) words.add(word)
  }
}

const body = [...words]
  .sort()
  .map((word) => `  ${JSON.stringify(word)},`)
  .join('\n')
writeFileSync(
  OUTPUT,
  `// Generated by scripts/build-password-blocklist.ts: do not edit by hand.
// Most used passwords that meet the length rule, lower-cased. Source: SecLists (MIT licence,
// Daniel Miessler), xato-net top 300,000 and NCSC top 100,000.
export const COMMON_PASSWORDS: ReadonlySet<string> = new Set([
${body}
])
`,
)
console.log(`${words.size} passwords written to ${OUTPUT}`)
